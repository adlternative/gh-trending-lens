const DEFAULT_LANG = "en";
let LANG = DEFAULT_LANG;

function setLang(lang) {
  LANG = STRINGS[lang] ? lang : DEFAULT_LANG;
  return LANG;
}
const getLang = () => LANG;

function t(key, vars) {
  const table = STRINGS[LANG] || STRINGS[DEFAULT_LANG];
  const s = table[key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

const catLabel = (id) => t(`cat.${id}`);
const subLabel = (catId, subId) => (subId === "misc" ? t("sub.misc") : t(`sub.${catId}.${subId}`));

if (typeof module !== "undefined") module.exports = { LANGS, STRINGS, DEFAULT_LANG, setLang, getLang, t, catLabel, subLabel };
